"""Первая программа на Python: вывод текста на экран.

Запуск:
    python seminars/seminar_01_intro_to_python/examples/01_hello_world.py
"""

# =============================================================================
# print() — вывод на экран
# =============================================================================
# print — это встроенная функция. Круглые скобки означают "вызвать функцию",
# а то, что внутри скобок, — данные, которые ей передают (аргументы).

print("Hello, world!")

# Строка — это текст в кавычках. Кавычки могут быть двойными или одинарными:
# "Привет" и 'Привет' — одно и то же. Одинарные удобны, когда внутри строки
# нужны двойные кавычки:
print('Преподаватель сказал: "добро пожаловать на курс"')

# =============================================================================
# Несколько аргументов
# =============================================================================
# print() умеет выводить несколько значений подряд — через запятую.
# Между ними автоматически ставится пробел.

print("Python", "версия", 3.12)

# Разделитель можно поменять параметром sep:
print("2026", "09", "28", sep="-")

# А символ в конце строки — параметром end (по умолчанию это перевод строки).
print("Загрузка", end="...")
print("готово")

# =============================================================================
# Вывод чисел и выражений
# =============================================================================
# В print() можно передать не только готовое значение, но и выражение —
# Python сначала вычислит его, а потом выведет результат.

print(2 + 2)
print(10 / 4)

# Пустой вызов print() просто переводит строку — удобно для отступов в выводе.
print()
print("Конец программы")
