# =============================================================================
# Переменная — имя для значения
# =============================================================================
# Знак = — это операция присваивания: "сохрани значение справа под именем слева".
# Читается не как "равно", а как "присвоить".

name = "Анна"
age = 19
height = 1.72

print(name, age, height)

# Переменной можно присвоить новое значение — старое просто забывается.
age = 20
print("Новый возраст:", age)

# Значение можно вычислить из других переменных.
next_year_age = age + 1
print("Через год:", next_year_age)

# =============================================================================
# Правила именования
# =============================================================================
# Имя переменной может состоять из букв, цифр и символа _, но не может
# начинаться с цифры. Регистр важен: age и Age — разные переменные.
#
# Можно так:        user_name, total2, _temp
# Нельзя так:       2total (начинается с цифры), user-name (дефис — это минус)
# Не стоит так:     class, print, input (это уже занятые в Python имена)
#
# По соглашению PEP 8 имена переменных пишут строчными буквами,
# слова разделяют подчёркиванием: total_price, student_count.

total_price = 1500
student_count = 12
print("Цена на одного:", total_price / student_count)

# =============================================================================
# Выражения и операции с числами
# =============================================================================
# Выражение — это то, что можно вычислить: 2 + 2, age * 2, name.
# Инструкция — это команда, которую Python выполняет: присваивание, вызов print().

a = 17
b = 5

print("Сложение:      ", a + b)
print("Вычитание:     ", a - b)
print("Умножение:     ", a * b)
print("Деление:       ", a / b)  # результат всегда дробный: 3.4
print("Целая часть:   ", a // b)  # 3
print("Остаток:       ", a % b)  # 2
print("Возведение:    ", a**2)  # 289

# Приоритет операций как в математике, скобки работают так же.
print((a + b) * 2)

# =============================================================================
# Операции со строками
# =============================================================================
# Для строк + означает склеивание (конкатенацию), а * — повторение.

first_name = "Иван"
last_name = "Петров"
full_name = first_name + " " + last_name
print(full_name)

print("-" * 30)
print("ха" * 3)

# =============================================================================
# Типы значений
# =============================================================================
# У каждого значения есть тип. Узнать его помогает функция type().

text_value = "текст"
int_value = 42
float_value = 3.14

print(type(text_value))  # <class 'str'>  — строка
print(type(int_value))  # <class 'int'>  — целое число
print(type(float_value))  # <class 'float'> — дробное число

# Складывать строку и число нельзя — Python сообщит об ошибке TypeError:
# print("возраст: " + 20)   # TypeError: can only concatenate str (not "int") to str

# =============================================================================
# Присваивание нескольких переменных
# =============================================================================
x, y = 10, 20
print("x =", x, "y =", y)

# Обмен значений в одну строку — приятная особенность Python.
x, y = y, x
print("после обмена: x =", x, "y =", y)
