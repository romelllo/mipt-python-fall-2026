"""Ввод данных: input() и преобразование типов.

Программа ждёт ввода с клавиатуры, поэтому запускать её нужно в терминале:
    python seminars/seminar_01_intro_to_python/examples/03_input_output.py
"""

# =============================================================================
# input() — чтение данных от пользователя
# =============================================================================
# input() показывает приглашение, ждёт, пока пользователь введёт текст
# и нажмёт Enter, и возвращает введённое значение.

name = input("Как вас зовут? ")
print("Приятно познакомиться,", name)

# =============================================================================
# input() ВСЕГДА возвращает строку
# =============================================================================
# Даже если пользователь ввёл 5, в переменной окажется строка "5".

value = input("Введите число: ")
print("Тип введённого значения:", type(value))
print("Умножение строки на 2 склеит её саму с собой:", value * 2)

# Чтобы считать, строку нужно преобразовать в число:
#   int()   — в целое число
#   float() — в дробное число

number = int(value)
print("Теперь это число, умножаем на 2:", number * 2)

# Часто преобразование пишут сразу вокруг input():
weight = float(input("Введите ваш вес в кг: "))
print("Через год при наборе 5% вес составит:", weight * 1.05)

# Если пользователь введёт не число, программа остановится с ошибкой
# ValueError: invalid literal for int() with base 10: 'привет'
# Как обрабатывать такие ситуации — разберём на семинаре 8.

# =============================================================================
# f-строки — удобный способ подставить значения в текст
# =============================================================================
# Буква f перед кавычками разрешает вставлять значения переменных
# в фигурных скобках прямо внутри строки.

age = int(input("Сколько вам лет? "))
print(f"{name}, через 10 лет вам будет {age + 10}")

# Без f-строки пришлось бы писать длиннее:
print(name + ", через 10 лет вам будет " + str(age + 10))

# str() делает обратное преобразование — из числа в строку.
