# =============================================================================
# Комментарии
# =============================================================================
# Всё, что идёт после символа #, Python игнорирует. Комментарии нужны людям:
# они объясняют, зачем написан код, а не повторяют то, что и так видно.

price = 500  # цена одного билета, руб.

# Многострочный комментарий — это просто несколько строк, начинающихся с #.
# Так удобно описывать целый кусок программы
# или временно отключать код, не удаляя его:
# print("эта строка не выполнится")

print("Цена билета:", price)

# =============================================================================
# Отступы выделяют блоки кода
# =============================================================================
# В большинстве языков блоки выделяют фигурными скобками, а в Python — отступами
# (4 пробела). Строки с одинаковым отступом образуют один блок.
#
# Конструкцию if подробно разберём на семинаре 2, здесь она нужна только
# чтобы показать, как работают отступы.

temperature = 30

if temperature > 25:
    # Эти две строки — тело условия, они выполнятся только если условие истинно
    print("Жарко!")
    print("Возьмите воды")

print("Эта строка без отступа — она выполняется всегда")

# Если сделать отступ там, где он не нужен, Python остановится с ошибкой:
#   IndentationError: unexpected indent
# А если забыть отступ после двоеточия:
#   IndentationError: expected an indented block

# =============================================================================
# Как читать сообщения об ошибках
# =============================================================================
# Ошибки — это нормальная часть программирования. Python всегда пишет,
# в каком файле, в какой строке и что именно ему не понравилось.
# Читать сообщение стоит С КОНЦА: последняя строка — суть проблемы.
#
# Четыре самые частые ошибки в начале пути:
#
# 1. SyntaxError — опечатка в самом тексте программы
#    print("привет"        -> SyntaxError: '(' was never closed
#
# 2. NameError — используется имя, которого не существует
#    print(nmae)           -> NameError: name 'nmae' is not defined
#
# 3. TypeError — операция не подходит для этих типов
#    "возраст: " + 20      -> TypeError: can only concatenate str (not "int") to str
#
# 4. ValueError — тип подходит, а само значение нет
#    int("привет")         -> ValueError: invalid literal for int() with base 10

# =============================================================================
# Модуль
# =============================================================================
# Этот файл целиком — модуль: обычный текстовый файл с расширением .py.
# Python выполняет инструкции модуля сверху вниз, одну за другой.

print("Последняя инструкция модуля")
