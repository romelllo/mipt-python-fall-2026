"""Типы данных: строки со спецсимволами и логический тип.

Запуск:
    python seminars/seminar_02_data_types_and_control_flow/examples/01_data_types.py
"""

# =============================================================================
# Строки: многострочные и спецсимволы
# =============================================================================
# Про кавычки, склеивание (+) и повторение (*) — семинар 1.
# Здесь — то, чего там не было.

# Тройные кавычки — строка на несколько строк:
menu = """Меню:
  - кофе
  - чай"""
print(menu)

# Спецсимволы начинаются с обратного слэша:
#   \n — перевод строки
#   \t — табуляция
#   \\ — сам обратный слэш
#   \" — кавычка такого же типа, как и у строки

print("Первая строка\nВторая строка")
print("Имя:\tАнна")
print("Имя:\tВладимир")
print("Путь к файлу: C:\\Users\\student")
print("Он сказал: \"привет\" — и ушёл, 'тихо'")

# =============================================================================
# Логический тип: True и False
# =============================================================================
# В логическом типе (bool) всего два значения. Пишутся с заглавной буквы.

is_student = True
is_working = False

print(is_student, type(is_student))

# =============================================================================
# Операции сравнения
# =============================================================================
# Результат сравнения — всегда True или False.

print(5 > 3)  # True
print(5 < 3)  # False
print(5 == 5)  # True   — == это СРАВНЕНИЕ
print(5 != 3)  # True   — не равно
print(5 >= 5)  # True
print(5 <= 4)  # False

# Внимание: = и == это разные вещи
# age = 18   — присвоить переменной значение 18
# age == 18  — проверить, равно ли значение 18

age = 19
print("Совершеннолетний:", age >= 18)

# Строки тоже сравниваются: по алфавиту, а на равенство — посимвольно
print("яблоко" > "банан")  # True — "я" идёт в алфавите после "б"
print("Привет" == "привет")  # False — регистр имеет значение

# =============================================================================
# Логические операторы: and, or, not
# =============================================================================
# and — истинно, когда истинны ОБА условия
# or  — истинно, когда истинно ХОТЯ БЫ ОДНО
# not — меняет значение на противоположное

sunny = True
warm = False
rainy = False

print(sunny and warm)  # False — для and нужны истинными оба
print(warm and sunny)  # False — порядок не важен
print(sunny or warm)  # True  — для or достаточно одного
print(warm or rainy)  # False — оба условия ложны
print(not sunny)  # False — отрицание True
print(not warm)  # True  — отрицание False

has_ticket = True
is_vip = False
is_adult = age >= 18

print("Пускаем на сеанс:", is_adult and has_ticket)  # True
print("Пускаем в VIP-зал:", is_adult and is_vip)  # False — нет VIP-статуса
print("Нужна проверка:", not is_adult or not has_ticket)  # False — всё в порядке

# =============================================================================
# Оператор in
# =============================================================================
# in проверяет, входит ли одна строка в другую.

print("кот" in "мой кот спит")  # True
print("пёс" in "мой кот спит")  # False
print("а" not in "Привет")  # True
