"""Условные конструкции: if, if-else, if-elif-else.

Запуск:
    python seminars/seminar_02_data_types_and_control_flow/examples/02_conditionals.py
"""

# =============================================================================
# if — сделать что-то, только если условие истинно
# =============================================================================
# После условия обязательно двоеточие, а тело пишется с отступом в 4 пробела
# (про отступы — семинар 1).

temperature = 30

if temperature > 25:
    print("Жарко, возьмите воды")

print("Эта строка выполняется всегда")

# =============================================================================
# if-else — одно из двух
# =============================================================================
age = 15

if age >= 18:
    print("Доступ разрешён")
else:
    print("Доступ запрещён")

# =============================================================================
# if-elif-else — выбор из нескольких вариантов
# =============================================================================
# Python проверяет условия сверху вниз и выполняет ПЕРВОЕ подошедшее.
# Остальные при этом не проверяются.

score = 75

if score >= 90:
    print("Отлично")
elif score >= 75:
    print("Хорошо")
elif score >= 60:
    print("Удовлетворительно")
else:
    print("Неудовлетворительно")

# Порядок условий важен: если поставить `score >= 60` первым,
# то при score = 95 программа напечатает «Удовлетворительно».

# =============================================================================
# Сложные условия: and, or
# =============================================================================
age = 20
has_ticket = True

if age >= 18 and has_ticket:
    print("Проходите в зал")

# То же самое через вложенные условия — работает, но читается хуже:
if age >= 18:
    if has_ticket:
        print("Проходите в зал")
    else:
        print("Купите билет")
else:
    print("Фильм только для взрослых")

# =============================================================================
# Частые ошибки
# =============================================================================
# 1. Одно = вместо двух в условии:
#       if age = 18:        -> SyntaxError
#       if age == 18:       -> правильно
#
# 2. Забытое двоеточие:
#       if age > 18         -> SyntaxError: expected ':'
#
# 3. Забытый отступ в теле:
#       if age > 18:
#       print("ок")         -> IndentationError: expected an indented block
#
# 4. Сравнение строки с числом:
#       input("Возраст: ") > 18   -> TypeError
#       нужно: int(input("Возраст: ")) > 18
