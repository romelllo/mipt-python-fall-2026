"""Циклы: while, for, range(), составные операторы, break и continue.

Запуск:
    python seminars/seminar_02_data_types_and_control_flow/examples/03_loops.py
"""

# =============================================================================
# while — пока условие истинно
# =============================================================================
# Используют, когда заранее неизвестно, сколько будет повторений.

count = 1
while count <= 5:
    print("Шаг", count)
    count += 1  # то же самое, что count = count + 1

# ВАЖНО: если забыть менять переменную из условия, цикл не закончится никогда.
# Прервать зависшую программу в терминале: Ctrl+C.

# =============================================================================
# Составные операторы присваивания
# =============================================================================
total = 10
total += 5  # total = total + 5  -> 15
total -= 3  # total = total - 3  -> 12
total *= 2  # total = total * 2  -> 24
print("Итого:", total)

# =============================================================================
# for и range() — когда количество повторений известно
# =============================================================================
# range(stop)              — от 0 до stop, не включая stop
# range(start, stop)       — от start до stop, не включая stop
# range(start, stop, step) — с шагом step

for number in range(5):
    print("range(5):", number)  # 0 1 2 3 4

for number in range(1, 6):
    print("range(1, 6):", number)  # 1 2 3 4 5

for number in range(0, 11, 2):
    print("чётное:", number)  # 0 2 4 6 8 10

# По строке тоже можно пройти — по одному символу:
for letter in "Python":
    print(letter)

# =============================================================================
# Накопление результата
# =============================================================================
# Приём, который встречается постоянно: завести переменную ДО цикла
# и изменять её внутри.

total = 0
for number in range(1, 101):
    total += number

print("Сумма чисел от 1 до 100:", total)

# =============================================================================
# break — досрочно выйти из цикла
# =============================================================================
for number in range(1, 11):
    if number == 5:
        print("Нашли 5, выходим")
        break
    print("Проверяем:", number)

# =============================================================================
# continue — пропустить текущий шаг и перейти к следующему
# =============================================================================
for number in range(1, 11):
    if number % 2 == 0:
        continue  # чётные пропускаем
    print("Нечётное:", number)
