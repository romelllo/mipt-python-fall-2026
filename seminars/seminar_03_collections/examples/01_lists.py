"""Списки: создание, индексация, срезы, изменение, перебор.

Запуск:
    python seminars/seminar_03_collections/examples/01_lists.py
"""

# =============================================================================
# Создание списка и получение количества элементов
# =============================================================================
# Список хранит несколько значений под одним именем, в заданном порядке.
# Записывается в квадратных скобках, элементы разделяются запятыми.

fruits = ["яблоко", "банан", "вишня"]
numbers = [10, 25, 3, 47, 8]
empty = []

print(fruits)
print("Элементов в списке:", len(fruits))
print("Пустой список:", empty, len(empty))

# В одном списке могут лежать значения разных типов (но так делают редко):
mixed = ["Анна", 19, True]
print(mixed)

# =============================================================================
# Индексация: обращение к элементу по номеру
# =============================================================================
# Нумерация начинается с НУЛЯ. Отрицательные индексы считают с конца
# и начинаются с -1.
#
#   индекс:     0         1        2
#            ["яблоко", "банан", "вишня"]
#   с конца:    -3        -2       -1

print(fruits[0])  # яблоко — первый элемент
print(fruits[2])  # вишня  — третий элемент
print(fruits[-1])  # вишня  — последний элемент
print(fruits[-2])  # банан  — предпоследний

# Обращение к несуществующему индексу — ошибка:
# print(fruits[3])   # IndexError: list index out of range

# =============================================================================
# Срезы: получение части списка
# =============================================================================
# Запись list[start:stop] возвращает элементы с start по stop, НЕ включая stop.

letters = ["a", "b", "c", "d", "e", "f"]

print(letters[1:4])  # ['b', 'c', 'd']
print(letters[:3])  # ['a', 'b', 'c']   — с начала
print(letters[3:])  # ['d', 'e', 'f']   — до конца
print(letters[:])  # весь список целиком
print(letters[::2])  # ['a', 'c', 'e']  — каждый второй (шаг 2)
print(letters[::-1])  # ['f', 'e', 'd', 'c', 'b', 'a'] — в обратном порядке

# =============================================================================
# Списки изменяемы
# =============================================================================
# В отличие от строк, элемент списка можно заменить.

fruits[0] = "груша"
print(fruits)  # ['груша', 'банан', 'вишня']

# =============================================================================
# Методы списка
# =============================================================================
# Метод — это действие, которое вызывается через точку у самого объекта.

fruits.append("киви")  # добавить в конец
print("append:", fruits)

fruits.insert(1, "слива")  # вставить по индексу
print("insert:", fruits)

fruits.remove("банан")  # удалить по значению
print("remove:", fruits)

last = fruits.pop()  # удалить последний и вернуть его
print("pop:", last, "->", fruits)

numbers.sort()  # отсортировать список на месте
print("sort:", numbers)

# =============================================================================
# Проверка наличия элемента
# =============================================================================
# Оператор in знаком с семинара 2: со списком он работает так же, как со строкой.

print("вишня" in fruits)  # True
print("манго" in fruits)  # False

# =============================================================================
# Перебор элементов списка
# =============================================================================
# Цикл for проходит по элементам списка — так же, как он проходил по строке.

total = 0
for number in numbers:
    total += number

print("Сумма чисел:", total)

for fruit in fruits:
    print("Фрукт:", fruit)
