"""Строка как последовательность символов, split() и join().

Запуск:
    python seminars/seminar_03_collections/examples/02_strings.py
"""

# =============================================================================
# Индексы и срезы работают со строками так же, как со списками
# =============================================================================

word = "Python"

print(word[0])  # P  — первый символ
print(word[-1])  # n  — последний символ
print(word[0:3])  # Pyt
print(word[:3])  # Pyt
print(word[3:])  # hon
print(word[::-1])  # nohtyP — строка задом наперёд
print(len(word))  # 6

# =============================================================================
# Но строка неизменяема
# =============================================================================
# Элемент списка заменить можно, а символ строки — нет:
#
#   word[0] = "J"   # TypeError: 'str' object does not support item assignment
#
# Вместо этого собирают новую строку:

new_word = "J" + word[1:]
print(new_word)  # Jython

# =============================================================================
# Перебор символов
# =============================================================================
for letter in "код":
    print(letter)

# =============================================================================
# Коды символов: ord() и chr()
# =============================================================================
# Каждому символу соответствует число — его код в таблице Unicode.

print(ord("A"))  # 65  — код символа
print(chr(66))  # B   — символ по коду

# =============================================================================
# split() — из строки в список
# =============================================================================
# Метод split() разрезает строку на части по разделителю и возвращает список.

sentence = "мама мыла раму"
words = sentence.split()  # без аргумента — по пробелам
print(words)  # ['мама', 'мыла', 'раму']
print("Слов в предложении:", len(words))

csv_line = "Анна,19,ФРКТ"
print(csv_line.split(","))  # ['Анна', '19', 'ФРКТ']

# =============================================================================
# join() — из списка в строку
# =============================================================================
# Метод join() собирает список строк в одну строку.
# Вызывается у разделителя: "разделитель".join(список)

names = ["Анна", "Иван", "Пётр"]
print(", ".join(names))  # Анна, Иван, Пётр
print(" и ".join(names))  # Анна и Иван и Пётр
print("".join(names))  # АннаИванПётр

# join() работает только со списком строк: ", ".join([1, 2, 3]) даст TypeError

# Вместе split() и join() позволяют обработать текст по словам:
sentence = "сегодня хорошая погода"
words = sentence.split()
print(" | ".join(words))
