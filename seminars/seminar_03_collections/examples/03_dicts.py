"""Словари: пары «ключ — значение».

Запуск:
    python seminars/seminar_03_collections/examples/03_dicts.py
"""

# =============================================================================
# Создание словаря
# =============================================================================
# В списке доступ к значению идёт по номеру, а в словаре — по ключу.
# Записывается в фигурных скобках: {ключ: значение, ...}

student = {
    "name": "Анна",
    "group": "Б01-123",
    "course": 1,
}

print(student)
print("Полей в словаре:", len(student))

empty = {}
print("Пустой словарь:", empty)

# =============================================================================
# Доступ к значению по ключу
# =============================================================================

print(student["name"])  # Анна
print(student["course"])  # 1

# Если ключа нет — ошибка:
# print(student["email"])   # KeyError: 'email'

# Безопасный способ — метод get(): вместо ошибки вернёт None
# или значение по умолчанию, если его указать.
print(student.get("email"))  # None
print(student.get("email", "не указан"))  # не указан

# =============================================================================
# Добавление, изменение и удаление
# =============================================================================

student["email"] = "anna@example.com"  # нового ключа не было — он добавился
student["course"] = 2  # ключ был — значение заменилось
print(student)

del student["email"]  # удалить пару по ключу
print(student)

# Проверка наличия КЛЮЧА (не значения):
print("name" in student)  # True
print("Анна" in student)  # False — это значение, а не ключ

# =============================================================================
# Перебор словаря
# =============================================================================

prices = {
    "кофе": 180,
    "чай": 120,
    "какао": 200,
}

# По ключам (вариант по умолчанию):
for item in prices:
    print(item, "стоит", prices[item])

# Явно по ключам, значениям и парам:
print(list(prices.keys()))  # ['кофе', 'чай', 'какао']
print(list(prices.values()))  # [180, 120, 200]

# items() даёт пары — их удобно сразу распаковать в две переменные:
for item, price in prices.items():
    print(f"{item}: {price} руб.")

total = 0
for price in prices.values():
    total += price

print("Сумма всех цен:", total)
