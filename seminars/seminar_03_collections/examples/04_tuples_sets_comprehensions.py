# =============================================================================
# Кортеж (tuple) — неизменяемый список
# =============================================================================
# Записывается в круглых скобках. Всё, что умеет список для чтения
# (индексы, срезы, len, перебор, in), работает и с кортежем.

point = (10, 20)
print(point, point[0], len(point))

# Но изменить кортеж нельзя:
# point[0] = 5   # TypeError: 'tuple' object does not support item assignment

# Кортежи используют там, где набор значений не должен меняться:
# координаты, размеры, запись «ключ — значение».

# Множественное присваивание (встречалось на семинаре 1) — это тоже кортежи:
x, y = point
print("x =", x, "y =", y)

# =============================================================================
# Множество (set) — коллекция уникальных элементов без порядка
# =============================================================================
# Записывается в фигурных скобках, как словарь, но без значений.

colors = {"красный", "зелёный", "синий"}
print(colors, len(colors))

# Дубликаты исчезают автоматически — отсюда главный приём:
numbers = [1, 2, 2, 3, 3, 3, 4]
unique = set(numbers)
print("Уникальные:", unique)
print("Сколько уникальных:", len(unique))

colors.add("жёлтый")  # добавить
colors.discard("синий")  # удалить, если есть
print("красный" in colors)  # проверка принадлежности

# Операции над множествами:
group_a = {"Анна", "Иван", "Пётр"}
group_b = {"Иван", "Мария"}

print("Объединение:", group_a | group_b)
print("Пересечение:", group_a & group_b)
print("Разность:", group_a - group_b)
print("Симметрическая разность:", group_a ^ group_b)

# У множества нет порядка, поэтому индексация не работает:
# colors[0]   # TypeError: 'set' object is not subscriptable

# =============================================================================
# Списочные выражения (list comprehensions)
# =============================================================================
# Короткая запись для создания списка из другого списка или range().

# Было (обычный цикл):
squares = []
for number in range(1, 6):
    squares.append(number**2)
print(squares)

# Стало (списочное выражение):
squares = [number**2 for number in range(1, 6)]
print(squares)

# С условием — берём только подходящие элементы:
evens = [number for number in range(1, 11) if number % 2 == 0]
print(evens)

words = ["python", "список", "словарь"]
lengths = [len(word) for word in words]
print(lengths)

# Читается так: «собрать <выражение> для каждого <элемента> из <коллекции>,
# если <условие>». Для длинных и сложных преобразований обычный цикл понятнее.
