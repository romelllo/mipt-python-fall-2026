# =============================================================================
# Множественное наследование
# =============================================================================
# Класс можно построить сразу на нескольких базовых: достаточно перечислить
# их в скобках через запятую.
class Employee:
    def report(self):
        return "отчёт сотрудника"


class SalaryEmployee(Employee):
    """Сотрудник, получающий зарплату."""

    def report(self):
        return "отчёт по зарплате"


class FinanciallyResponsiblePerson(Employee):
    """Материально ответственное лицо."""

    def report(self):
        return "отчёт материально ответственного"


class Bookkeeper(SalaryEmployee, FinanciallyResponsiblePerson):
    """Бухгалтер — и то, и другое одновременно."""


# =============================================================================
# Проблема «ромба»
# =============================================================================
# Иерархия замыкается в ромб: Bookkeeper -> два родителя -> общий Employee.
#
#            Employee
#            /      \
#   SalaryEmployee  FinanciallyResponsiblePerson
#            \      /
#           Bookkeeper
#
# Какой из двух методов report() вызовется? Ответ даёт порядок разрешения
# методов (MRO) — список классов, по которому Python ищет метод.

print(Bookkeeper().report())  # отчёт по зарплате — побеждает первый родитель

for klass in Bookkeeper.__mro__:
    print(" ->", klass.__name__)

# Поменяйте порядок родителей местами — и поведение класса изменится,
# хотя в самом Bookkeeper не поменяется ни строки. Именно поэтому
# множественного наследования стараются избегать: оно считается безопасным
# только для наследования интерфейсов без реализации.


# =============================================================================
# Проблема «круга-эллипса» и принцип подстановки Лисков
# =============================================================================
# В математике квадрат — частный случай прямоугольника. Казалось бы,
# наследование напрашивается.
class Rectangle:
    """Прямоугольник, у которого можно менять стороны."""

    def __init__(self, width, height):
        self.width = width
        self.height = height

    def set_width(self, value):
        self.width = value

    def area(self):
        return self.width * self.height


class Square(Rectangle):
    """Квадрат: у него стороны всегда равны."""

    def __init__(self, side):
        super().__init__(side, side)

    def set_width(self, value):
        self.width = value
        self.height = value  # иначе квадрат перестанет быть квадратом


def widen(figure):
    """Увеличить ширину фигуры вдвое, не трогая высоту."""
    figure.set_width(figure.width * 2)
    return figure.area()


rectangle = Rectangle(3, 4)
square = Square(3)

print("Прямоугольник:", widen(rectangle))  # 24 — как и ожидается
print("Квадрат:", widen(square))  # 36, а ожидалось 18

# Функция widen() написана для прямоугольников и для них работает верно,
# а на квадрате даёт неожиданный результат.
#
# Это нарушение ПРИНЦИПА ПОДСТАНОВКИ ЛИСКОВ (LSP): код, работающий
# с базовым классом, должен работать и с любым его наследником,
# ничего о нём не зная.

# =============================================================================
# Другие проблемы наследования
# =============================================================================
# «Хрупкий базовый класс» — наследники опираются не только на интерфейс
#     базового класса, но и на его устройство. Любое изменение базового класса
#     рискует сломать всех наследников сразу.
#
# «Йо-йо» — чтобы понять, что делает один метод, приходится прыгать вверх-вниз
#     по длинной цепочке наследников.
#
# «Взрыв классов» — иерархия разрастается так, что становится сложнее задачи,
#     которую решает.
#
# Общий вывод лекции: по возможности предпочитать композицию наследованию,
# не строить глубокие иерархии и не нарушать инкапсуляцию.
