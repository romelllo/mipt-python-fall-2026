# =============================================================================
# Аннотации типов
# =============================================================================
# Аннотация указывает, какой тип ожидается у аргумента и что функция вернёт.
# На работу программы она НЕ влияет: это подсказка человеку и инструментам
# проверки (ty, встроенный анализатор редактора).
def repeat(text: str, times: int) -> str:
    """Повторить строку нужное число раз."""
    return text * times


print(repeat("ха", 3))

