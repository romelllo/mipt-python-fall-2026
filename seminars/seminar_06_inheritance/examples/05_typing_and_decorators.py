# =============================================================================
# @property — вычисляемый атрибут
# =============================================================================
# Иногда значение нужно считать на лету, но обращаться к нему хочется
# как к обычному атрибуту, без скобок. Для этого есть декоратор @property.
class Employee:
    """Сотрудник с вычисляемой годовой зарплатой."""

    def __init__(self, name: str, monthly_salary: int) -> None:
        self.name = name
        self.monthly_salary = monthly_salary

    @property
    def yearly_salary(self) -> int:
        """Годовая зарплата — считается при каждом обращении."""
        return self.monthly_salary * 12


employee = Employee("Анна", 150_000)
print(employee.yearly_salary)  # без скобок, как обычный атрибут

employee.monthly_salary = 160_000
print(employee.yearly_salary)  # значение пересчиталось само

