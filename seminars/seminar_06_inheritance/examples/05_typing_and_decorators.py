# =============================================================================
# Декораторы
# =============================================================================
# Декоратор — функция, которая «оборачивает» другую функцию, добавляя
# поведение вокруг её вызова. Это работает потому, что функции в Python —
# обычные объекты (семинар 4).
def with_logging(function):
    """Печатать имя функции и результат при каждом вызове."""

    def wrapper(*args, **kwargs):
        print(f"вызов {function.__name__} с аргументами {args}")
        result = function(*args, **kwargs)
        print(f"результат: {result}")
        return result

    return wrapper


@with_logging
def add(first, second):
    return first + second


add(2, 3)

