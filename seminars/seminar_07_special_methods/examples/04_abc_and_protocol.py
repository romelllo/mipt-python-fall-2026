"""Абстрактные классы и протоколы: как описать ожидаемый интерфейс.

Тема для самостоятельного изучения (обещана на семинаре 6).

Запуск:
    python seminars/seminar_07_special_methods/examples/04_abc_and_protocol.py
"""

from abc import ABC, abstractmethod
from typing import Protocol, runtime_checkable

# =============================================================================
# Проблема
# =============================================================================
# На семинаре 6 мы видели утиную типизацию: функции неважно, какого класса
# объект, лишь бы у него был нужный метод. Обратная сторона — об отсутствии
# метода мы узнаём только в момент вызова, когда программа уже упала.
#
# Есть два способа описать ожидаемый интерфейс заранее.


# =============================================================================
# Способ 1: абстрактный базовый класс (abc)
# =============================================================================
# Класс, унаследованный от ABC, нельзя создать напрямую — он существует
# только для того, чтобы от него наследовались. Методы, помеченные
# декоратором @abstractmethod, наследник ОБЯЗАН определить.
class Sensor(ABC):
    """Базовый класс датчика."""

    def __init__(self, address):
        self.address = address

    @abstractmethod
    def read(self):
        """Вернуть показание датчика. Наследник обязан это реализовать."""

    def describe(self):
        """Обычный метод: достаётся наследникам как есть."""
        return f"Датчик {self.address}: {self.read()}"


class TemperatureSensor(Sensor):
    def read(self):
        return 21.5


class HumiditySensor(Sensor):
    def read(self):
        return 48


print(TemperatureSensor("192.168.1.10").describe())
print(HumiditySensor("192.168.1.11").describe())

# Попытка создать сам Sensor или наследника без read() завершится ошибкой:
#
#   Sensor("192.168.1.12")
#   TypeError: Can't instantiate abstract class Sensor with abstract method read
#
# Это и есть польза: об ошибке становится известно сразу при создании объекта,
# а не когда-нибудь потом при вызове метода.


# =============================================================================
# Способ 2: протокол (Protocol)
# =============================================================================
# Протокол описывает, ЧТО объект должен уметь, не требуя наследования.
# Это формальная запись утиной типизации: классу достаточно иметь
# подходящие методы.
@runtime_checkable
class Readable(Protocol):
    """Всё, у чего можно получить показание."""

    def read(self) -> float: ...


class WaterMeter:
    """Счётчик воды: про Readable ничего не знает и ни от кого не наследуется."""

    def read(self) -> float:
        return 134.7


def show_reading(device: Readable) -> None:
    """Напечатать показание любого объекта, который умеет read()."""
    print("Показание:", device.read())


show_reading(WaterMeter())
show_reading(TemperatureSensor("192.168.1.10"))

# Декоратор @runtime_checkable разрешает проверку во время работы программы:
print(isinstance(WaterMeter(), Readable))  # True
print(isinstance("текст", Readable))  # False

# =============================================================================
# Что выбрать
# =============================================================================
# ABC       — когда у классов есть общий код, который хочется переиспользовать,
#             и наследование уместно по смыслу («является»).
# Protocol  — когда нужен только интерфейс и наследование навязывать не хочется;
#             чужие классы под протокол подходят сами собой.
#
# Рекомендация из лекции 6: если речь идёт о наследовании одного интерфейса
# без реализации, используйте Protocol.
