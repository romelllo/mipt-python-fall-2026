# =============================================================================
# Какие бывают ошибки
# =============================================================================
# 1. Синтаксические — Python находит их ещё до запуска программы:
#        if x > 0         <- забыли двоеточие: SyntaxError
#
# 2. Логические — программа работает, но делает не то, что задумано:
#        if age < 18:     <- а должно было быть <=
#    Python о них не знает, их ловят тестами и внимательностью.
#
# 3. Ошибки времени выполнения — возникают во время работы программы:
#        int("двадцать")  -> ValueError
#        10 / 0           -> ZeroDivisionError
#        [1, 2][5]        -> IndexError
#        {"a": 1}["b"]    -> KeyError
#        open("nope.txt") -> FileNotFoundError
#
# Сегодня разбираемся с третьим видом. Когда происходит такая ошибка,
# Python создаёт ИСКЛЮЧЕНИЕ — объект, описывающий, что случилось.
# Если исключение никто не перехватил, программа завершается и печатает
# traceback.

# =============================================================================
# Специальное значение или исключение
# =============================================================================
# Сообщить об ошибке можно по-разному. У строк есть два метода поиска:
text = "hello"

print(text.find("l"))  # 2
print(text.find("z"))  # -1 — «не нашёл»

# Проблема специального значения: его легко забыть проверить.
# -1 — вполне допустимый индекс (последний символ), поэтому такая ошибка
# не роняет программу, а тихо даёт неправильный результат:
position = text.find("z")
print(text[position])  # 'o' — совсем не то, что мы искали

# index() в той же ситуации бросает исключение — забыть про него не получится:
#     text.index("z")  ->  ValueError: substring not found


# =============================================================================
# try / except
# =============================================================================
# Код, который может упасть, кладём в try. Реакцию на ошибку — в except.
# Если в try ошибки не было, except пропускается.
for text in ["42", "двадцать"]:
    try:
        number = int(text)
        print("Получили число", number)
    except ValueError:
        print(f"{text!r} — это не целое число")


# =============================================================================
# Несколько except и объект исключения
# =============================================================================
# Разные ошибки обрабатываются по-разному. Через «as» можно получить сам
# объект исключения — при печати он показывает сообщение об ошибке.
def divide(a_text, b_text):
    """Разделить два числа, записанных строками."""
    try:
        result = int(a_text) / int(b_text)
    except ValueError:
        print(f"Нужны целые числа, получено {a_text!r} и {b_text!r}")
    except ZeroDivisionError as error:
        print("Ошибка:", error)
    else:
        print(f"{a_text} / {b_text} = {result}")


divide("10", "4")  # 10 / 4 = 2.5
divide("10", "ноль")  # Нужны целые числа...
divide("10", "0")  # Ошибка: division by zero

# Если реакция одинаковая, типы можно перечислить в кортеже:
#     except (ValueError, ZeroDivisionError):


# =============================================================================
# else и finally
# =============================================================================
# else   — выполняется, только если в try НЕ было исключения;
# finally — выполняется ВСЕГДА: и после ошибки, и без неё, и даже после return.
def show_square(text):
    try:
        number = int(text)
    except ValueError:
        print("  except: это не число")
        return
    else:
        print("  else: квадрат равен", number**2)
    finally:
        print("  finally: проверка завершена")


print("show_square('7'):")
show_square("7")
print("show_square('семь'):")
show_square("семь")  # finally сработал, хотя в except был return

# Зачем else, если можно дописать строку в конец try? Чтобы в try оставалась
# только строка, которая может упасть. Иначе except может случайно поймать
# ошибку из совсем другой строки.


# =============================================================================
# Файл, которого нет (обещано на семинаре 5)
# =============================================================================
# with сам закроет файл, а try/except не даст программе упасть.
for path in ["data/readings.txt", "data/missing.txt"]:
    try:
        with open(path, encoding="utf-8") as file:
            lines = file.readlines()
    except FileNotFoundError:
        print(f"Файл {path} не найден — проверьте, из какой папки запущена программа")
    else:
        print(f"В файле {path} строк: {len(lines)}")


# =============================================================================
# LBYL против EAFP
# =============================================================================
# LBYL (Look Before You Leap, «семь раз отмерь»): сначала проверяем, потом
# делаем. Попробуем заранее проверить, что строка — целое число:
def is_int_lbyl(text):
    return text.isdigit()


# Сразу видно проблемы: isdigit() не пропустит минус и пробелы, хотя
# int() их понимает. Чиним — и проверка обрастает новыми условиями:
def is_int_lbyl_better(text):
    text = text.strip()
    if text.startswith(("-", "+")):
        text = text[1:]
    return text.isdigit()


# ...но она всё ещё не знает про «1_000» (int это понимает) и про
# символы вроде «²», для которых isdigit() возвращает True, а int() падает.
#
# EAFP (Easier to Ask Forgiveness than Permission, «легче попросить
# прощения»): просто пробуем и обрабатываем ошибку. int() сам лучше всех
# знает, что он умеет разбирать.
def is_int_eafp(text):
    try:
        int(text)
    except ValueError:
        return False
    return True


print()
print(f"{'строка':>10} | {'LBYL':>5} | {'LBYL+':>5} | {'EAFP':>5}")
for text in ["42", " 42 ", "-7", "1_000", "²", "", "4.2"]:
    print(
        f"{text!r:>10} | {is_int_lbyl(text)!s:>5} | "
        f"{is_int_lbyl_better(text)!s:>5} | {is_int_eafp(text)!s:>5}"
    )
# Колонка EAFP всегда совпадает с тем, что на самом деле сделает int().
# В Python принят стиль EAFP.


# =============================================================================
# Типичные ошибки новичков
# =============================================================================
# 1. Голый except (или except Exception) ловит ВСЁ — даже опечатки в коде:
#
#        try:
#            number = int(txet)    <- опечатка, NameError
#        except:
#            print("Введите число")  <- сообщение врёт, опечатку не найти
#
# 2. except ... pass — ошибка молча исчезает:
#
#        try:
#            save(data)
#        except OSError:
#            pass                   <- данные не сохранились, а никто не знает
#
# 3. Слишком большой try — непонятно, какая из двадцати строк упала,
#    и легко поймать не ту ошибку. В try кладём минимум кода.
#
# Правило: перехватывайте только те исключения, которые ожидаете
# и знаете, как обработать.
