"""Задание 1.2. Средняя скорость.

Программа считает среднюю скорость по расстоянию (км) и времени в пути (ч).
Обработайте две ошибки по-разному:
    - ввели не число       -> «Расстояние и время должны быть числами»
    - время равно нулю     -> «Время в пути не может быть нулевым»
Если ошибок нет, выведите скорость с одним знаком после точки.
Строка «Расчёт окончен» должна печататься в любом случае.
"""

distance_text = input("Расстояние, км: ")
hours_text = input("Время в пути, ч: ")

# TODO: посчитайте скорость так, чтобы обе ошибки не роняли программу,
#       а давали своё сообщение
speed = float(distance_text) / float(hours_text)

# TODO: выведите скорость, только если расчёт прошёл без ошибок
print(f"Средняя скорость: {speed:.1f} км/ч")

# TODO: эта строка должна печататься всегда — и при ошибке, и без неё
print("Расчёт окончен")
