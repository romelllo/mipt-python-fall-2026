path = "data/readings.txt"

# TODO: если файла нет — сообщите об этом, программа не должна падать
with open(path, encoding="utf-8") as file:
    lines = file.readlines()

values = []
# enumerate() выдаёт пары (номер, строка); start=1 — нумерация с единицы
for line_number, line in enumerate(lines, start=1):
    values.append(float(line))
    # TODO: это сообщение должно появляться только для испорченных строк,
    #       а обработка остальных строк — продолжаться
    print(f"Строка {line_number} пропущена: {line.strip()!r}")

