"""Задание 2.1. Разбор времени.

Функция parse_time(text) принимает время в формате «ЧЧ:ММ» и возвращает число
минут от начала суток. При неправильных данных она бросает ValueError
с понятным сообщением:

    '09:30'   -> 570
    '24:00'   -> ошибка: Часы должны быть от 0 до 23, получено 24
    '12:75'   -> ошибка: Минуты должны быть от 0 до 59, получено 75
    'полдень' -> ошибка: Ожидался формат ЧЧ:ММ, получено 'полдень'

Сама функция ничего не печатает — печатает вызывающий код.
"""


def parse_time(text):
    """Перевести время «ЧЧ:ММ» в минуты от начала суток."""
    parts = text.split(":")
    # TODO: если частей не две — сообщите об ошибке формата

    hours = int(parts[0])
    minutes = int(parts[1])
    # TODO: если часы не от 0 до 23 — сообщите об ошибке
    # TODO: если минуты не от 0 до 59 — сообщите об ошибке

    return hours * 60 + minutes


for text in ["09:30", "23:59", "24:00", "12:75", "полдень", "ab:cd"]:
    # TODO: для каждой строки выведите результат или сообщение об ошибке,
    #       программа не должна останавливаться на первой же ошибке
    print(f"{text!r} -> {parse_time(text)}")
