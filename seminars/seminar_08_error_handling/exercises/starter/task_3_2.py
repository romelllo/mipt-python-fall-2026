class LibraryError(Exception):
    """Базовая ошибка библиотеки."""


class BookNotFoundError(LibraryError):
    """Такой книги в библиотеке нет."""

    def __init__(self, title):
        super().__init__(f"Книги «{title}» нет в библиотеке")
        self.title = title


