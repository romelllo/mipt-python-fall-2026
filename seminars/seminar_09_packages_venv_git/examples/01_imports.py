"""Формы import и почему не стоит писать import *.

Запуск:
    python seminars/seminar_09_packages_venv_git/examples/01_imports.py
"""

# =============================================================================
# import модуль — подключить модуль целиком
# =============================================================================
# Модуль — это файл с кодом на Python. После import модуль доступен
# по своему имени, а его функции — через точку.
import datetime as dt
import math
import sys
from math import pi, sqrt

print(math.sqrt(16))  # 4.0
print(math.sin(math.pi / 6))  # 0.49999999999999994 — почти 0.5, это float

# Модуль — обычный объект. dir() показывает, какие имена в нём есть:
print([name for name in dir(math) if not name.startswith("_")][:10])


# =============================================================================
# from модуль import имя — взять отдельные имена
# =============================================================================
# Импорт выше в файле: from math import pi, sqrt.
# Теперь pi и sqrt доступны без приставки math.
print(sqrt(25), pi)

# Плюс: код короче. Минус: глядя на sqrt(), не видно, откуда она взялась.
# Для пары часто используемых имён это нормально.


# =============================================================================
# import модуль as псевдоним
# =============================================================================
# Импорт выше в файле: import datetime as dt.
print(dt.date.today())

# Псевдонимы уместны для длинных имён и общепринятых сокращений:
#     import numpy as np
#     import pandas as pd
# Придумывать свои сокращения для коротких модулей не стоит.


# =============================================================================
# Почему не import *
# =============================================================================
# from модуль import * подключает ВСЕ имена модуля. Они молча заменяют
# одноимённые имена в вашей программе — в том числе встроенные:
#
#     from gzip import *
#
#     file = open("notes.txt", "w")  # это уже gzip.open, а не встроенный open!
#     file.write("Привет")
#     # TypeError: a bytes-like object is required, not 'str'
#
# А если звёздочек несколько, уже невозможно понять, чья функция вызывается:
#
#     from bz2 import *
#     from gzip import *
#     from lzma import *
#     open("file")   # bz2.open? gzip.open? lzma.open? — последний импорт победил
#
# Поэтому в программах import * не используют. Исключение — быстрые опыты
# в интерактивной консоли.


# =============================================================================
# Модуль импортируется один раз
# =============================================================================
# Повторный import того же модуля ничего не делает: Python запоминает уже
# загруженные модули. Это видно по словарю sys.modules.
print("math" in sys.modules)  # True — модуль уже загружен
