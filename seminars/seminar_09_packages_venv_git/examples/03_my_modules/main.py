"""Программа из нескольких файлов: свой модуль и свой пакет.

Структура папки:
    03_my_modules/
    ├── main.py          <- этот файл, его и запускаем
    ├── greetings.py     <- свой модуль
    └── geometry/        <- свой пакет
        ├── __init__.py
        ├── circle.py
        └── rectangle.py

Запуск:
    python seminars/seminar_09_packages_venv_git/examples/03_my_modules/main.py

Python ищет модули сначала в папке запущенного файла, поэтому main.py
находит greetings.py и geometry/ рядом с собой, откуда бы его ни запустили.
"""

# =============================================================================
# Свой модуль
# =============================================================================
# При импорте Python ВЫПОЛНЯЕТ весь файл greetings.py — вы увидите строку
# «Выполняется greetings.py, __name__ = 'greetings'». А вот проверки
# под if __name__ == "__main__" не выполнятся.
import greetings

# =============================================================================
# Свой пакет
# =============================================================================
# Модуль из пакета подключают через точку или через from.
# Обратите внимание: в circle и rectangle есть функции с одинаковыми
# именами area — обращение через имя модуля не даёт им перепутаться.
from geometry import circle, rectangle
from geometry.rectangle import perimeter

print(greetings.greet("Аня"))
print(greetings.farewell())
print(greetings.DEFAULT_NAME)  # переменные модуля тоже доступны

print(f"Площадь круга радиуса 2: {circle.area(2):.2f}")
print(f"Площадь прямоугольника 3×4: {rectangle.area(3, 4)}")
print(f"Периметр прямоугольника 3×4: {perimeter(3, 4)}")

# Модуль — тоже объект: у него есть тип и атрибуты
print(type(greetings))  # <class 'module'>
print(greetings.__name__)  # greetings

# После первого запуска рядом появится папка __pycache__: там Python хранит
# скомпилированные модули, чтобы в следующий раз импорт был быстрее.
# Её не нужно хранить в Git — она есть в .gitignore.
