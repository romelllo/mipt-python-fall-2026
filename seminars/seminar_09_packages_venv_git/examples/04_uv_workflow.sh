#!/usr/bin/env bash
# Проект и зависимости с uv: команды по порядку с пояснениями.
#
# Этот файл можно просто читать и набирать команды в терминале по одной —
# так и стоит делать на семинаре. А можно запустить целиком (macOS / Linux /
# Git Bash на Windows): он всё сделает во временной папке и ничего не оставит
# в репозитории курса.
#
#     bash seminars/seminar_09_packages_venv_git/examples/04_uv_workflow.sh
#
# Нужен интернет: uv скачивает библиотеку tqdm с PyPI.

set -e # остановиться на первой же ошибке

WORKDIR=$(mktemp -d) # временная папка — подальше от репозитория курса
cd "$WORKDIR"
echo "Работаем в $WORKDIR"

# =============================================================================
# 1. Создать проект
# =============================================================================
# --python 3.12 — минимальная версия Python для проекта. Без этого флага uv
# возьмёт самую новую версию, которая есть на компьютере.
uv init --python 3.12 habit-tracker
cd habit-tracker

# Что появилось:
#   pyproject.toml   — описание проекта и список зависимостей
#   .python-version  — версия Python для этого проекта
#   main.py          — заготовка программы
#   README.md        — описание
#   .gitignore       — что не хранить в Git (uv заодно сделал папку репозиторием)
ls -A
cat pyproject.toml

# =============================================================================
# 2. Запустить программу в окружении проекта
# =============================================================================
# uv run сам создаёт виртуальное окружение .venv (если его ещё нет)
# и запускает программу его интерпретатором.
uv run main.py

# Посмотрим, какой интерпретатор работает в каждом случае:
cat >where_am_i.py <<'EOF'
import sys

print("Интерпретатор:", sys.executable)
print("Версия:", sys.version.split()[0])
EOF

echo "--- через uv run (окружение проекта):"
uv run where_am_i.py
echo "--- напрямую (системный Python):"
python3 where_am_i.py || python where_am_i.py

# =============================================================================
# 3. Установить внешнюю библиотеку
# =============================================================================
# uv add:
#   - скачивает библиотеку и ставит её в .venv;
#   - записывает её в pyproject.toml (раздел dependencies);
#   - фиксирует точные версии всех пакетов в uv.lock.
uv add tqdm
grep -A 3 "dependencies" pyproject.toml

# uv tree показывает зависимости проекта и зависимости зависимостей
uv tree

cat >progress.py <<'EOF'
import time

from tqdm import tqdm

for day in tqdm(range(20), desc="Дни"):
    time.sleep(0.05)
EOF
uv run progress.py

# Через системный Python библиотека не найдётся — её там нет:
#     python3 progress.py
#     ModuleNotFoundError: No module named 'tqdm'
python3 progress.py 2>&1 | tail -1 || true

# =============================================================================
# 4. Воспроизвести окружение «на другом компьютере»
# =============================================================================
# .venv не передают другим и не хранят в Git. Удалим её — как будто проект
# только что скачали:
rm -rf .venv

# uv sync создаёт окружение заново строго по uv.lock — с теми же версиями.
uv sync
uv run progress.py

# =============================================================================
# 5. Версия Python для проекта
# =============================================================================
# uv python pin записывает версию в .python-version; при необходимости uv
# скачает её сам. Версия должна подходить под requires-python из pyproject.toml.
uv python pin 3.13
uv run where_am_i.py

# =============================================================================
# 6. Удалить библиотеку
# =============================================================================
uv remove tqdm
grep -A 1 "dependencies" pyproject.toml

echo "Готово. Временную папку можно удалить: rm -rf $WORKDIR"
