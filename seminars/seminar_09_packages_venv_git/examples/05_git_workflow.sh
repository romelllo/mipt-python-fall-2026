#!/usr/bin/env bash
# Основы Git: команды по порядку с пояснениями.
#
# Этот файл можно просто читать и набирать команды в терминале по одной —
# так и стоит делать на семинаре. А можно запустить целиком (macOS / Linux /
# Git Bash на Windows): он всё сделает во временной папке и ничего не изменит
# в репозитории курса.
#
#     bash seminars/seminar_09_packages_venv_git/examples/05_git_workflow.sh
#
# Перед первым коммитом Git должен знать ваше имя и почту (делается один раз):
#     git config --global user.name "Иван Иванов"
#     git config --global user.email "ivan@example.com"

set -e # остановиться на первой же ошибке
export GIT_PAGER=cat # печатать вывод git log/diff сразу, без постраничного просмотра

WORKDIR=$(mktemp -d) # временная папка — подальше от репозитория курса
cd "$WORKDIR"
echo "Работаем в $WORKDIR"

# Если имя и почта не настроены глобально, зададим их только для этого
# временного репозитория, чтобы пример отработал.
git_local_identity() {
    git config user.name >/dev/null || git config user.name "Example Student"
    git config user.email >/dev/null || git config user.email "student@example.com"
}

# =============================================================================
# 1. Создать репозиторий
# =============================================================================
# git init превращает папку в репозиторий: появляется скрытая папка .git,
# в которой Git хранит всю историю. Руками её не трогаем.
# (uv init делает это сам — в проектах uv отдельный git init не нужен.)
mkdir diary
cd diary
git init -b main # -b main — назвать основную ветку main (иногда по умолчанию master)
git_local_identity

# =============================================================================
# 2. status — главная команда
# =============================================================================
# Новые файлы Git сам не отслеживает: он показывает их как untracked.
echo "print('Мой дневник')" >main.py
git status

# =============================================================================
# 3. add + commit — сохранить снимок
# =============================================================================
# git add выбирает, ЧТО войдёт в следующий коммит (staging area).
# git commit сохраняет выбранное в историю с сообщением.
git add main.py
git status --short # A  main.py — файл подготовлен
git commit -m "Add main.py"

# =============================================================================
# 4. Изменения: diff, commit, log
# =============================================================================
echo "print('Запись 1: начал вести дневник')" >>main.py
git diff # строки с + добавлены, с - удалены
git add main.py
git commit -m "Add first entry"

# История: каждый коммит — хеш, автор, дата, сообщение
git log --oneline

# Что именно поменялось в последнем коммите:
git show --stat HEAD

# =============================================================================
# 5. restore — отменить несохранённые изменения
# =============================================================================
echo "это всё испортит" >main.py # случайно перезаписали файл
git status --short                # M main.py — файл изменён
git restore main.py               # вернуть версию из последнего коммита
cat main.py

# =============================================================================
# 6. .gitignore — что не хранить в репозитории
# =============================================================================
echo "отладка" >debug.log
echo "password=123" >secrets.txt
git status --short # ?? debug.log и ?? secrets.txt — Git их видит

printf '*.log\nsecrets.txt\n__pycache__/\n.venv\n' >.gitignore
git status --short # остался только ?? .gitignore — лишнего Git больше не видит

git add .gitignore # сам .gitignore коммитим: это правило для всех
git commit -m "Add .gitignore"
git log --oneline

echo "Готово. Временную папку можно удалить: rm -rf $WORKDIR"
