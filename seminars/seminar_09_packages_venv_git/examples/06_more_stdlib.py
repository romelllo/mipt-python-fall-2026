"""Обзор других модулей стандартной библиотеки.

Тема для самостоятельного изучения.

Запуск:
    python seminars/seminar_09_packages_venv_git/examples/06_more_stdlib.py
"""

import os
import reprlib
import statistics
import sys
import textwrap
from collections import Counter
from contextlib import suppress
from decimal import Decimal
from enum import Enum
from fractions import Fraction
from itertools import combinations
from pprint import pprint

# =============================================================================
# decimal и fractions — точные дроби
# =============================================================================
# float хранит числа в двоичном виде, поэтому десятичные дроби в нём
# приближённые. Это свойство компьютерной арифметики, а не ошибка Python.
print(0.1 * 3)  # 0.30000000000000004

# Decimal считает в десятичной системе — точно, но медленнее.
# Создавайте Decimal из СТРОКИ: Decimal(0.1) унаследует неточность float.
print(Decimal("0.1") * 3)  # 0.3

# Fraction — обыкновенные дроби
print(Fraction(1, 3) + Fraction(1, 4))  # 7/12


# =============================================================================
# statistics — описательная статистика
# =============================================================================
scores = [72, 85, 90, 64, 85, 99, 78]
print(statistics.mean(scores))  # среднее
print(statistics.median(scores))  # медиана
print(statistics.mode(scores))  # самое частое значение: 85
print(round(statistics.stdev(scores), 2))  # стандартное отклонение


# =============================================================================
# textwrap, pprint, reprlib — аккуратный вывод
# =============================================================================
text = (
    "В начале июля, в чрезвычайно жаркое время, под вечер один молодой "
    "человек вышел из своей каморки, которую нанимал от жильцов в С-м "
    "переулке, на улицу и медленно, как бы в нерешимости, отправился "
    "к К-ну мосту."
)
print(textwrap.fill(text, width=40))  # перенос по ширине 40 символов
print(textwrap.shorten(text, width=50))  # обрезать с многоточием

# pprint печатает вложенные структуры по строкам
pprint({"Аня": [5, 4, 5], "Боря": [3, 4], "Вика": [5, 5, 5, 4]}, width=30)

# reprlib.repr сокращает огромные объекты, чтобы не завесить консоль
print(reprlib.repr(list(range(1_000_000))))  # [0, 1, 2, 3, 4, 5, ...]


# =============================================================================
# collections.Counter — подсчёт элементов
# =============================================================================
sentence = "мама мыла раму а рама мыла маму"
counter = Counter(sentence.split())
print(counter["мыла"])  # 2
print(counter.most_common(2))  # [('мыла', 2), ('мама', 1)]
print(Counter("абракадабра").most_common(1))  # [('а', 5)]


# =============================================================================
# enum — набор именованных вариантов
# =============================================================================
# Вместо «магических» строк и чисел — понятные имена, опечатку в которых
# сразу заметит Python.
class Difficulty(Enum):
    EASY = 1
    NORMAL = 2
    HARD = 3


level = Difficulty.NORMAL
print(level, level.name, level.value)  # Difficulty.NORMAL NORMAL 2
print(level == Difficulty.HARD)  # False


# =============================================================================
# itertools — комбинаторика и удобные итераторы
# =============================================================================
# Все пары игроков для турнира «каждый с каждым»:
for pair in combinations(["Аня", "Боря", "Вика"], 2):
    print(pair)


# =============================================================================
# contextlib.suppress — подавить ожидаемое исключение
# =============================================================================
# То же самое, что try / except FileNotFoundError: pass, но короче.
# Подходит, только когда исключение действительно не важно (семинар 8).
with suppress(FileNotFoundError):
    os.remove("файл_которого_нет.tmp")
print("Программа продолжила работу")


# =============================================================================
# sys и os — сведения об интерпретаторе и системе
# =============================================================================
print(sys.version.split()[0])  # версия Python
print(sys.executable)  # путь к интерпретатору — в .venv он будет другим
print(sys.platform)  # 'darwin', 'linux' или 'win32'

print(os.getcwd())  # текущая папка — от неё считаются относительные пути
print(sorted(os.listdir("."))[:5])  # первые файлы текущей папки
print(os.getenv("HOME") or os.getenv("USERPROFILE"))  # домашняя папка


