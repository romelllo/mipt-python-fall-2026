import random
import time

# TODO: подключите из библиотеки tqdm функцию для полосы прогресса

days = 30
done_days = 0

# TODO: сделайте так, чтобы при переборе дней рисовалась полоса прогресса
#       с подписью «Обработка дней»
for _ in range(days):  # _ — номер дня нам не нужен, важно только количество
    time.sleep(0.05)  # имитируем долгую обработку одного дня
    if random.random() < 0.7:  # в 70% дней привычка выполнена
        done_days += 1

print(f"Привычка выполнена в {done_days} из {days} дней")
