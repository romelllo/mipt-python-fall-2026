"""Эхо-сервер: возвращает клиенту его же сообщение заглавными буквами.

Запуск (в отдельном окне терминала):
    python seminars/seminar_10_networking_sockets/examples/01_echo_server.py

Затем в другом окне запустите клиент 02_echo_client.py.
Остановить сервер — Ctrl+C.
"""

import socket

HOST = "127.0.0.1"  # «этот компьютер»: подключиться можно только с него самого
PORT = 8000  # номер порта: по нему ОС поймёт, что пакет адресован нашей программе

# create_server создаёт TCP-сокет, привязывает его к адресу и начинает слушать.
# with закроет сокет при выходе — даже если программа завершится с ошибкой.
with socket.create_server((HOST, PORT)) as server:
    print(f"Сервер слушает {HOST}:{PORT}. Остановить — Ctrl+C")

    while True:  # обслуживаем клиентов по очереди, одного за другим
        # accept() ждёт («блокируется»), пока кто-нибудь не подключится.
        # Возвращает НОВЫЙ сокет для разговора с этим клиентом и его адрес.
        conn, addr = server.accept()
        print("Подключился клиент", addr)

        with conn:
            while True:  # разговор с одним клиентом: много сообщений подряд
                data = conn.recv(1024)  # до 1024 байт; ждёт, пока они придут
                if not data:  # пустые байты b"" — клиент закрыл соединение
                    break
                text = data.decode("utf-8")  # байты → строка
                print("Получено:", text)
                conn.sendall(text.upper().encode("utf-8"))  # строка → байты

        print("Клиент отключился", addr)
